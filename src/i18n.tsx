export type TranslationKey = keyof typeof en;
type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string;

type I18nValue = { language: Language; setLanguage: (language: Language) => void; t: Translate };
const I18nContext = createContext<I18nValue | null>(null);
const storageKey = "resource-timeline-language";

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => localStorage.getItem(storageKey) === "zh-CN" ? "zh-CN" : "en");
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage(next) { localStorage.setItem(storageKey, next); setLanguageState(next); },
    t(key, values) {
      let text = (language === "zh-CN" ? zhCN : en)[key];
      for (const [name, value] of Object.entries(values ?? {})) text = text.split(`{${name}}`).join(String(value));
      return text;
    }
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
